"""由 `just binsync` 调用：按 manga/src/*.py 生成 manga/bin/ 下的命令垫片。

规则：模块名下划线转横线即命令名（如 convert_image_format_to → convert-image-format-to）；
下划线开头的模块（_common、本文件）不生成；默认规则表达不了的特例见 EXTRA_COMMANDS。

只有新增/删除/重命名脚本，或改了垫片模板，才需要重跑；平时改脚本代码不用跑。
"""
import argparse
import sys
from pathlib import Path

SRC_DIR = Path(__file__).resolve().parent
BIN_DIR = SRC_DIR.parent / "bin"

MARKER = "# Auto-generated by `just binsync`. DO NOT EDIT."

# 命令名 -> (模块名, 固定参数)：默认规则表达不了的特例放这里
# （曾有的 convert-cn/chinese-numbers-to-arab 已删除，统一用 cn-numbers-rename，
# 需要 replace 风格时手动加 --style replace）
EXTRA_COMMANDS = {}

TEMPLATE = """#!/usr/bin/env bash
{MARKER}
root="$(cd "$(dirname "$0")/../.." && pwd)"
exec uv run --project "$root/manga" python "$root/manga/src/{module}.py"{fixed} "$@"
"""


def collect_commands() -> dict:
    """返回 {命令名: (模块名, 固定参数)}。"""
    commands = {}
    for mod in sorted(SRC_DIR.glob("*.py")):
        if mod.stem.startswith("_"):
            continue
        name = mod.stem.replace("_", "-")
        if name in commands:
            raise ValueError(f"命令名冲突: {name}")
        commands[name] = (mod.stem, [])
    for name, (module, fixed) in EXTRA_COMMANDS.items():
        commands[name] = (module, list(fixed))
    return commands


def render(module: str, fixed: list) -> str:
    fixed_str = "".join(f" {a}" for a in fixed)
    return TEMPLATE.format(MARKER=MARKER, module=module, fixed=fixed_str)


def sync(out_dir: Path, check: bool = False) -> int:
    """生成/校验垫片。check 模式只对比不写文件；返回 0=已同步，1=有差异。"""
    commands = collect_commands()
    out_dir.mkdir(parents=True, exist_ok=True)
    added, updated = [], []
    for name, (module, fixed) in commands.items():
        content = render(module, fixed)
        path = out_dir / name
        if not path.exists():
            added.append(name)
            if not check:
                path.write_text(content, encoding="utf-8")
                path.chmod(0o755)
        elif path.read_text(encoding="utf-8") != content:
            updated.append(name)
            if not check:
                path.write_text(content, encoding="utf-8")
                path.chmod(0o755)
    removed = []
    for path in sorted(out_dir.iterdir()):
        if path.is_file() and path.name not in commands:
            try:
                head = path.read_text(encoding="utf-8")[:500]
            except (OSError, UnicodeDecodeError):
                continue
            if MARKER in head:
                removed.append(path.name)
                if not check:
                    path.unlink()
    if check:
        diffs = added + updated + removed
        if diffs:
            print(f"❌ bin/ 不同步: 新增{added} 修改{updated} 删除{removed}，请跑 just binsync")
            return 1
        print("✅ bin/ 已同步")
        return 0
    print(f"✅ binsync 完成：新增 {len(added)}，更新 {len(updated)}，删除 {len(removed)}")
    for name in added:
        print(f"  ＋ {name}（新命令，记得在 ~/.zshrc 配个别名）")
    for name in removed:
        print(f"  － {name}（已删除，对应别名可清理）")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="按 manga/src/*.py 生成 manga/bin/ 命令垫片")
    parser.add_argument("--check", action="store_true", help="只校验不同步，不写文件")
    parser.add_argument("--out", default=str(BIN_DIR), help="垫片输出目录（默认 manga/bin）")
    args = parser.parse_args(argv)
    return sync(Path(args.out), check=args.check)


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""由 `just binsync` 调用：向仓库根目录 bin/ 生成全部全局命令垫片。

全仓库唯一一套命令生成机制（原先 manga/src/_binsync.py 那套已并入本文件）。
来源：
- manga/src/*.py            → uv 垫片（模块名下划线转横线即命令名，下划线开头跳过）
- epub/src/*.py             → uv 垫片（同上规则）
- epub/shell script/*.sh    → 直调垫片（去 .sh 后缀，下划线转横线）
- other/*.py                → python3 直调垫片（零依赖脚本，同上规则）
- ffmpeg / ffprobe          → bin/ 下的相对软链（见 LINKED_BINARIES）
- 默认规则表达不了的特例     → EXTRA_COMMANDS

只有新增/删除/重命名脚本，或改了垫片模板，才需要重跑；平时改脚本代码不用跑。
用户 `$PATH` 只需包含 bin/ 这一个目录。
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_BIN_DIR = ROOT / "bin"

MARKER = "# Auto-generated by `just binsync`. DO NOT EDIT."

UV_TEMPLATE = """#!/usr/bin/env bash
{MARKER}
root="$(cd "$(dirname "$0")/.." && pwd)"
exec uv run --project "$root/{project}" python "$root/{script}"{fixed} "$@"
"""

PY_TEMPLATE = """#!/usr/bin/env bash
{MARKER}
root="$(cd "$(dirname "$0")/.." && pwd)"
exec python3 "$root/{script}"{fixed} "$@"
"""

SH_TEMPLATE = """#!/usr/bin/env bash
{MARKER}
root="$(cd "$(dirname "$0")/.." && pwd)"
exec "$root/{script}" "$@"
"""

# 命令名 -> (仓库内相对脚本路径, 固定参数)：默认规则表达不了的特例放这里
# 例：{"convert-cn": ("manga/src/cn_numbers_rename.py", ["--style", "replace"])}
EXTRA_COMMANDS: dict[str, tuple[str, list[str]]] = {}

# 仓库根目录下需要软链到 bin/ 的可执行文件（ffmpeg/ffprobe 由 git-lfs 跟踪，本体不入 bin/）
LINKED_BINARIES = ["ffmpeg", "ffprobe"]


def _fixed_suffix(fixed: list[str]) -> str:
    return "".join(f" {a}" for a in fixed)


def render(script: str, fixed: list[str] | None = None) -> str:
    """按脚本路径选模板：manga|epub/src 走 uv，other/ 走 python3，epub/shell script 走直调。"""
    fixed_str = _fixed_suffix(fixed or [])
    if script.startswith("other/"):
        return PY_TEMPLATE.format(MARKER=MARKER, script=script, fixed=fixed_str)
    if script.endswith(".sh"):
        if fixed_str:
            raise ValueError(f"shell 脚本垫片不支持固定参数: {script}")
        return SH_TEMPLATE.format(MARKER=MARKER, script=script)
    project = Path(script).parts[0]
    return UV_TEMPLATE.format(
        MARKER=MARKER, project=project, script=script, fixed=fixed_str)


def collect() -> dict[str, str]:
    """返回 {命令名: 垫片内容}，跨来源重名直接报错。"""
    commands: dict[str, str] = {}

    def add(name: str, script: str, where: str) -> None:
        if name in commands:
            raise ValueError(f"命令名冲突: {name}（{where}）")
        commands[name] = render(script)

    for project in ("manga", "epub"):
        for mod in sorted((ROOT / project / "src").glob("*.py")):
            if mod.stem.startswith("_"):
                continue
            rel = f"{project}/src/{mod.name}"
            add(mod.stem.replace("_", "-"), rel, rel)
    for sh in sorted((ROOT / "epub/shell script").glob("*.sh")):
        rel = f"epub/shell script/{sh.name}"
        add(sh.stem.replace("_", "-"), rel, rel)
    for mod in sorted((ROOT / "other").glob("*.py")):
        if mod.stem.startswith("_"):
            continue
        rel = f"other/{mod.name}"
        add(mod.stem.replace("_", "-"), rel, rel)

    # 特例最后加：同名时覆盖上面的默认命令
    for name, (script, fixed) in EXTRA_COMMANDS.items():
        if not (ROOT / script).exists():
            raise ValueError(f"EXTRA_COMMANDS 指向的脚本不存在: {script}")
        commands[name] = render(script, list(fixed))
    return commands


def sync_links(out_dir: Path, added: list, updated: list, check: bool) -> list[str]:
    """维护 ffmpeg/ffprobe 相对软链。返回警告信息。

    只创建/纠正 LINKED_BINARIES 里的软链；bin/ 下其它软链一律不动（可能在 $PATH 上
    有别的用途），也不参与差异统计，避免 --check 误报。
    """
    warnings = []
    for name in LINKED_BINARIES:
        src = ROOT / name
        dst = out_dir / name
        target = Path("..") / name
        if dst.is_symlink() and dst.readlink() == target:
            continue
        (updated if dst.exists() or dst.is_symlink() else added).append(name)
        if not check:
            if dst.is_symlink() or dst.exists():
                dst.unlink()
            dst.symlink_to(target)
        if not src.exists():
            warnings.append(f"{name} 不存在，软链指向空")
    return warnings


def sync(out_dir: Path, check: bool = False) -> int:
    """生成/校验垫片。check 模式只对比不写文件；返回 0=已同步，1=有差异。"""
    try:
        commands = collect()
    except ValueError as e:
        print(f"❌ {e}", file=sys.stderr)
        return 1

    out_dir.mkdir(parents=True, exist_ok=True)
    conflicts = [n for n in commands if (out_dir / n).is_dir()]
    if conflicts:
        print(f"❌ bin/ 下有同名目录，无法生成垫片: {conflicts}", file=sys.stderr)
        return 1
    added, updated, removed = [], [], []
    for name, content in commands.items():
        path = out_dir / name
        try:
            current = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            current = None  # 不存在 / 断链 / 非文本（二进制同名文件）
        if current == content:
            continue
        (added if current is None and not path.exists() and not path.is_symlink()
         else updated).append(name)
        if not check:
            if path.is_symlink() or path.exists():
                path.unlink()
            path.write_text(content, encoding="utf-8")
            path.chmod(0o755)

    # 清理来源已消失的垫片：只删带本工具 MARKER 的普通文件，软链与手写脚本不动
    for path in sorted(out_dir.iterdir()):
        if path.is_symlink() or not path.is_file() or path.name in commands:
            continue
        try:
            head = path.read_text(encoding="utf-8")[:500]
        except (OSError, UnicodeDecodeError):
            continue
        if MARKER in head:
            removed.append(path.name)
            if not check:
                path.unlink()

    # 软链只在真实 bin/ 目录里维护，--out 到临时目录时跳过（便于测试）
    is_real_bin = out_dir.resolve() == DEFAULT_BIN_DIR.resolve()
    warnings = [] if not is_real_bin else sync_links(out_dir, added, updated, check)
    for w in warnings:
        print(f"⚠️  {w}", file=sys.stderr)

    if check:
        if added or updated or removed:
            print(f"❌ bin/ 不同步: 新增{added} 修改{updated} 删除{removed}，请跑 just binsync")
            return 1
        print("✅ bin/ 已同步")
        return 0

    print(f"✅ binsync 完成：新增 {len(added)}，更新 {len(updated)}，"
          f"删除 {len(removed)}，共 {len(commands)} 个命令")
    for n in added:
        print(f"  ＋ {n}")
    for n in updated:
        print(f"  ~ {n}")
    for n in removed:
        print(f"  － {n}")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="生成 bin/ 下的全仓库命令垫片")
    parser.add_argument("--check", action="store_true", help="只校验不同步，不写文件")
    parser.add_argument("--out", default=str(DEFAULT_BIN_DIR),
                        help="垫片输出目录（默认仓库根 bin/）")
    args = parser.parse_args(argv)
    return sync(Path(args.out), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
